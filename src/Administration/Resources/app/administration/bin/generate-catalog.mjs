// Erzeugt den Katalog der Erweiterungspunkte, den @callora/admin als Typ ausliefert.
//
// Zwei Ausgaben aus einem Lauf:
//   src/core/extensions/catalog.json          Rohdaten inklusive Fundort
//   src/core/extensions/catalog.generated.ts  die Typ-Unions AdminSlot und AdminHook
//
//   npm run generate:catalog
//
// Das Lesen steckt in scan-extension-points.ts und ist dort ohne Dateisystem getestet;
// hier läuft nur der Dateilauf drumherum. Deshalb `--experimental-strip-types` im
// npm-Skript: Diese Datei importiert das TypeScript-Modul direkt, statt eine zweite
// Fassung derselben Regeln zu führen.
//
// Die CI ruft das Skript und schlägt bei einem Diff fehl. Ein verschobener Slot ließe
// sonst `@callora/admin` einen Punkt versprechen, den es nicht mehr gibt.

import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

import { scanExtensionPoints } from '../src/core/extensions/scan-extension-points.ts'

const root = fileURLToPath(new URL('..', import.meta.url))
const scanRoot = join(root, process.argv[2] ?? 'src')
const outputDir = join(root, 'src', 'core', 'extensions')

// Sortiert und rekursiv, damit zwei Läufe auf zwei Rechnern dieselbe Reihenfolge
// ergeben — der Diff-Gate der CI vergliche sonst Dateisystem-Launen.
function sourceFiles(directory) {
  const found = []
  for (const entry of readdirSync(directory).sort()) {
    if (entry === 'node_modules' || entry === 'dist' || entry === 'dist-lib') {
      continue
    }
    const path = join(directory, entry)
    if (statSync(path).isDirectory()) {
      found.push(...sourceFiles(path))
      continue
    }
    // Testdateien bleiben draußen: Der Test des Scanners zitiert runHook('…') als
    // Beispiel, und ein Beispiel darf nie zu einem Vertrag werden.
    if (/\.(test|spec)\.(ts|js)$/.test(entry)) {
      continue
    }
    if (/\.(vue|ts)$/.test(entry)) {
      found.push(path)
    }
  }
  return found
}

const points = []
for (const file of sourceFiles(scanRoot)) {
  const relativePath = relative(scanRoot, file).split(sep).join('/')
  points.push(...scanExtensionPoints(readFileSync(file, 'utf8'), relativePath))
}

const dedupe = (kind) => {
  const seen = new Set()
  return points.filter((point) => {
    if (point.kind !== kind || seen.has(point.name)) {
      return false
    }
    seen.add(point.name)
    return true
  })
}

const slots = dedupe('slot')
const hooks = dedupe('hook')

writeFileSync(join(outputDir, 'catalog.json'), `${JSON.stringify({ slots, hooks }, null, 2)}\n`)

const union = (entries) =>
  entries
    .map((entry) => entry.name)
    .sort()
    .map((name) => `  | '${name}'`)
    .join('\n')

writeFileSync(
  join(outputDir, 'catalog.generated.ts'),
  `// GENERATED by bin/generate-catalog.mjs — do not edit by hand.
// Regenerate with: npm run generate:catalog

/**
 * Every slot the shell renders. A plugin passing a name that is not in this union does not
 * compile — where the field registers extension points as free strings and a typo is a silent
 * no-op.
 */
export type AdminSlot =
${union(slots)}

/**
 * Every hook the shell runs. A name ending in '*' is assembled at runtime from a prefix, so only
 * the family is knowable statically.
 */
export type AdminHook =
${union(hooks)}
`,
)

console.log(`catalog: ${slots.length} slots, ${hooks.length} hooks`)
